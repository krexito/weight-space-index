"""
External benchmark: can zero-forward-pass wsi features predict measured single-neuron behaviour effects?
=========================================================================================================
Labels (NOT generated by us): Naik, Liu & Gangal, "Auto Weight-Space Programming, Part 1" (2026),
github.com/atharva-naik/auto-weight-space-programming, runs/round4/levers_pilot.json and levers_pilot_b.json
(copied to benchmarks/awsp_sycophancy/labels/, MIT). For 802 Qwen3.5-4B MLP neurons (layers 3,6,9,12,18,24,27,30)
they ran the model with the neuron switched off (x0), doubled (x2) and clamped to its strong-firing value (clamp),
and measured the change in sycophancy (soft_pf, 96 MMLU-style items) and math (GSM8K answer log-prob, 96 problems),
separately on two disjoint halves of the items. Their linear probe on the raw down_proj column predicted none of the
signed clamp/sycophancy effect on held-out layers (R^2 = -0.0095).

PRE-REGISTERED PROTOCOL (written before any correlation was computed; every feature and target is reported):
  Features, weights only (no forward pass):
    write_norm        ||down_proj[:, n]||
    letter_spread     std over the 4 answer letters of the logit lens U_eff @ col (letters ' A'..' D' and 'A'..'D')
    letter_maxabs     max |logit lens| over the answer letters
    agree_proj        mean logit lens on agreement tokens minus disagreement tokens (signed)
    key_pressure      mean E_in[pressure tokens] . gate key (signed; gate rows scaled by the pre-MLP norm gain)
    downstream_read   sum over the next 3 layers of ||K_eff(l')^T col|| (how strongly later MLP keys read the write)
    wsi_composite     mean rank of write_norm, letter_spread, downstream_read   <- PRIMARY magnitude predictor
  Reference that is NOT zero-pass (uses the activation statistic `strong` measured by the label authors on Wikipedia):
    act_x_norm        |strong| * write_norm
  Targets: mean of the two halves, for x0/x2/clamp x syco/math.
  Metrics: Spearman(feature, |effect|) for magnitude (all neurons, and mean within-layer);
           Spearman(feature, effect) for signed features; noise ceiling = split-half Spearman of |A| vs |B| (and A vs B).
  PRIMARY test: Spearman(wsi_composite, |clamp/syco|) over all neurons, bootstrap 95% CI and permutation p-value.
"""

import json
import sys
import time
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "wsr"))

from wsi import WeightSpaceIndex  # noqa: E402
from wsi.indexer import get_mlp_input_keys  # noqa: E402

MODEL_DIR = ROOT / "models" / "qwen35-4b"
OUT_DIR = ROOT / "benchmarks" / "awsp_sycophancy"
LABELS = [OUT_DIR / "labels" / "levers_pilot.json", OUT_DIR / "labels" / "levers_pilot_b.json"]

LETTERS = [[" A", "A"], [" B", "B"], [" C", "C"], [" D", "D"]]
AGREE = [" Yes", "Yes", " yes", " right", " correct", " sorry", " Sorry", " apologize", " indeed", " agree", " You"]
DISAGREE = [" No", "No", " no", " incorrect", " wrong", " disagree", " However", " actually", " Actually"]
PRESSURE = [" sure", " Are", " think", " doubt", " wrong", " believe", " actually", " really", " confident", " suggest"]
INTERVENTIONS = ["x0", "x2", "clamp"]
BEHAVIOURS = ["syco", "math"]


def spearman(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    ra, rb = np.argsort(np.argsort(a)), np.argsort(np.argsort(b))
    if ra.std() == 0 or rb.std() == 0:
        return float("nan")
    return float(np.corrcoef(ra, rb)[0, 1])


def single_ids(tok, words):
    ids = []
    for w in words:
        t = tok.encode(w, add_special_tokens=False)
        if len(t) == 1:
            ids.append(t[0])
    return sorted(set(ids))


def main():
    t0 = time.time()
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(str(MODEL_DIR))

    # ---------------- labels
    rows, seen = [], set()
    for f in LABELS:
        for r in json.load(open(f, encoding="utf-8"))["rows"]:
            key = (r["layer"], r["n"])
            if key in seen:
                continue
            seen.add(key)
            r["source"] = f.stem
            rows.append(r)
    layers = sorted({r["layer"] for r in rows})
    print(f"{len(rows)} labelled neurons, layers {layers}", flush=True)

    # ---------------- weights (zero forward passes)
    I = WeightSpaceIndex(str(MODEL_DIR), lazy=True)
    anat, ck = I.anat, I.ck
    n_layers = len(anat.layers)
    U = I.U_eff
    E = I.E_in
    letter_ids = [single_ids(tok, v) for v in LETTERS]
    agree_ids, dis_ids, press_ids = single_ids(tok, AGREE), single_ids(tok, DISAGREE), single_ids(tok, PRESSURE)
    print("letter ids", letter_ids, "agree", len(agree_ids), "disagree", len(dis_ids), "pressure", len(press_ids), flush=True)
    U_let = [U[ids] for ids in letter_ids]
    U_ag, U_dis = U[agree_ids], U[dis_ids]
    E_pr = E[press_ids]
    d_ff = None

    key_cache = {}

    def keys(l):
        if l not in key_cache:
            K, _ = get_mlp_input_keys(ck, anat, l, d_ff)
            key_cache[l] = K  # [hidden, d_ff]
        return key_cache[l]

    feats = {k: np.zeros(len(rows)) for k in
             ["write_norm", "letter_spread", "letter_maxabs", "agree_proj", "key_pressure", "downstream_read"]}
    t_feat = time.time()
    by_layer = {}
    for i, r in enumerate(rows):
        by_layer.setdefault(r["layer"], []).append(i)
    for l, idx in by_layer.items():
        W = ck.get(anat.mlp_out(l)).float()  # [hidden, d_ff]
        if W.shape[0] != anat.hidden:
            W = W.t()
        d_ff = W.shape[1]
        ns = [rows[i]["n"] for i in idx]
        C = W[:, ns]  # [hidden, k]
        feats["write_norm"][idx] = C.norm(dim=0).numpy()
        L = torch.stack([(Ul @ C).mean(0) for Ul in U_let])  # [4, k]
        feats["letter_spread"][idx] = L.std(0).numpy()
        feats["letter_maxabs"][idx] = L.abs().max(0).values.numpy()
        feats["agree_proj"][idx] = ((U_ag @ C).mean(0) - (U_dis @ C).mean(0)).numpy()
        K = keys(l)[:, ns]
        feats["key_pressure"][idx] = (E_pr @ K).mean(0).numpy()
        ds = torch.zeros(len(ns))
        for l2 in range(l + 1, min(l + 4, n_layers)):
            ds += (keys(l2).t() @ C).norm(dim=0)
        feats["downstream_read"][idx] = ds.numpy()
        for l2 in list(key_cache):
            if l2 <= l:
                key_cache.pop(l2)
        print(f"  layer {l}: {len(ns)} neurons, {time.time() - t0:.1f}s", flush=True)
    t_feat = time.time() - t_feat

    def rank(x):
        return np.argsort(np.argsort(x)).astype(float)

    feats["wsi_composite"] = (rank(feats["write_norm"]) + rank(feats["letter_spread"]) + rank(feats["downstream_read"])) / 3
    strong = np.array([r["strong"] for r in rows])
    feats["act_x_norm (uses activation, not zero-pass)"] = np.abs(strong) * feats["write_norm"]
    lay = np.array([r["layer"] for r in rows])

    # ---------------- evaluation
    results = {"targets": {}}
    rng = np.random.default_rng(0)
    signed_feats = ["agree_proj", "key_pressure"]
    for iv in INTERVENTIONS:
        for beh in BEHAVIOURS:
            A = np.array([r[iv][beh][0] for r in rows])
            B = np.array([r[iv][beh][1] for r in rows])
            M = (A + B) / 2
            t = {"noise_ceiling_magnitude_split_half": spearman(np.abs(A), np.abs(B)),
                 "noise_ceiling_signed_split_half": spearman(A, B),
                 "magnitude": {}, "signed": {}}
            for name, f in feats.items():
                within = [spearman(f[lay == l], np.abs(M)[lay == l]) for l in layers]
                t["magnitude"][name] = {"all": spearman(f, np.abs(M)), "within_layer_mean": float(np.nanmean(within))}
            for name in signed_feats:
                f = feats[name]
                within = [spearman(f[lay == l], M[lay == l]) for l in layers]
                t["signed"][name] = {"all": spearman(f, M), "within_layer_mean": float(np.nanmean(within))}
                if iv == "clamp":
                    fs = f * np.sign(strong)
                    t["signed"][name + " x sign(strong) (uses activation sign)"] = {"all": spearman(fs, M)}
            results["targets"][f"{iv}/{beh}"] = t

    # primary test
    f = feats["wsi_composite"]
    M = np.abs(np.array([(r["clamp"]["syco"][0] + r["clamp"]["syco"][1]) / 2 for r in rows]))
    obs = spearman(f, M)
    boots = [spearman(f[s], M[s]) for s in (rng.integers(0, len(f), len(f)) for _ in range(2000))]
    perms = [spearman(f, rng.permutation(M)) for _ in range(2000)]
    results["primary"] = {
        "test": "Spearman(wsi_composite, |clamp/syco|), all neurons",
        "spearman": obs, "ci95": [float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))],
        "perm_p_one_sided": float((np.sum(np.array(perms) >= obs) + 1) / (len(perms) + 1)),
        "noise_ceiling": results["targets"]["clamp/syco"]["noise_ceiling_magnitude_split_half"],
    }
    results.update({
        "n_neurons": len(rows), "layers": layers, "model": "Qwen/Qwen3.5-4B",
        "forward_passes_used_by_wsi": 0, "feature_time_s": round(t_feat, 2), "total_time_s": round(time.time() - t0, 2),
        "label_source": "atharva-naik/auto-weight-space-programming runs/round4/levers_pilot{,_b}.json",
        "label_cost_reported_s": [json.load(open(f, encoding="utf-8")).get("sec") for f in LABELS],
        "their_probe_r2_heldout_layers_signed_clamp_syco": -0.0095,
    })
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "results.json").write_text(json.dumps(results, indent=1), encoding="utf-8")

    # ---------------- print
    print("\n=== PRIMARY ===")
    print(json.dumps(results["primary"], indent=1))
    for k, t in results["targets"].items():
        print(f"\n--- {k}  ceiling |A|vs|B| = {t['noise_ceiling_magnitude_split_half']:+.3f}   A vs B = {t['noise_ceiling_signed_split_half']:+.3f}")
        for name, v in t["magnitude"].items():
            print(f"   |eff| {name:48s} all {v['all']:+.3f}   within-layer {v['within_layer_mean']:+.3f}")
        for name, v in t["signed"].items():
            w = v.get("within_layer_mean")
            print(f"   sign  {name:48s} all {v['all']:+.3f}" + (f"   within-layer {w:+.3f}" if w is not None else ""))
    print(f"\nfeatures in {t_feat:.2f}s, total {time.time() - t0:.1f}s, 0 forward passes")


if __name__ == "__main__":
    main()
